import {
  readFileSync,
  readdirSync,
  openSync,
  readSync,
  closeSync,
  mkdirSync,
  existsSync,
  writeFileSync,
  rmSync,
} from "fs";
import { join, dirname, extname, isAbsolute, normalize, relative } from "path";

/**
 * Formats a file's content before it is written. Return the content unchanged
 * for files it doesn't know how to format.
 */
export type Formatter = (
  content: string,
  filePath: string,
) => string | Promise<string>;

/** The parts of the `prettier` module `prettierFormatter` needs. */
export type PrettierLike = {
  resolveConfig(filePath: string): Promise<object | null>;
  getFileInfo(filePath: string): Promise<{ inferredParser: string | null }>;
  format(source: string, options: object): Promise<string>;
};

/**
 * Formats with prettier, using the `.prettierrc` that applies to each file and
 * skipping files prettier has no parser for.
 * Usage: `format: prettierFormatter(await import("prettier"))`.
 */
export function prettierFormatter(prettier: PrettierLike): Formatter {
  return async (content, filePath) => {
    if (!(await prettier.getFileInfo(filePath)).inferredParser) return content;
    const config = await prettier.resolveConfig(filePath);
    return prettier.format(content, { ...config, filepath: filePath });
  };
}

export class FileReader {
  protected root: string;
  constructor(root: string) {
    this.root = root;
  }

  readFile(filePath: string) {
    return readFileSync(join(this.root, filePath), "utf-8");
  }
}

export enum FileWriteMode {
  initialise = "initialise",
  write = "write",
  append = "append",
}

type fileChange = { mode: FileWriteMode; content: string };

type ChangeMap = {
  [filePath: string]: fileChange;
};

export type PlannedAction = "create" | "update" | "remove" | "unchanged";

export type PlannedChange = {
  /** Relative to the root `FileWriter`. */
  file: string;
  action: PlannedAction;
  /** The final content, for `create` and `update`. */
  content?: string;
};

export type WriteMetrics = {
  created: number;
  updated: number;
  removed: number;
  unchanged: number;
  /** Lines in created and updated files, after formatting. */
  linesInChanges: number;
  /** Every file that was (or, in check mode, would be) created, updated or removed. */
  changed: PlannedChange[];
};

/** Marks a file as ours, so stale copies can be told apart from other tools' files. */
const GENERATED_MARKER = "generated by codegen-engine";
const GENERATED_HEADER = `@${GENERATED_MARKER}. Do not edit.`;
const headerByExtension: Record<string, string> = {
  py: `# ${GENERATED_HEADER}\n`,
  ts: `// ${GENERATED_HEADER}\n`,
  tsx: `// ${GENERATED_HEADER}\n`,
  js: `// ${GENERATED_HEADER}\n`,
  md: `<!-- ${GENERATED_HEADER} -->\n`,
};

/** Whether `file` is `dir` or inside it. Both are relative to the same root. */
function isWithin(file: string, dir: string) {
  const rel = relative(dir, file);
  return !rel.startsWith("..") && !isAbsolute(rel);
}

/**
 * Whether the file's first line has the generated marker. Only the first 100
 * characters are checked, so a huge first line (e.g. minified output) isn't
 * read in full.
 */
function hasGeneratedHeader(fullPath: string) {
  const buffer = Buffer.alloc(400); // 100 characters of UTF-8 at most
  const fd = openSync(fullPath, "r");
  try {
    const bytes = readSync(fd, buffer, 0, buffer.length, 0);
    const firstLine = buffer.toString("utf-8", 0, bytes).split("\n", 1)[0] ?? "";
    return firstLine.slice(0, 100).includes(GENERATED_MARKER);
  } finally {
    closeSync(fd);
  }
}

export class FileWriter extends FileReader {
  private changes: ChangeMap = {};
  /** Directories we generate into, so our unstaged files in them get removed. */
  private owned = new Set<string>();

  constructor(root: string) {
    super(root);
  }

  stageFileChange(relative_file: string, mode: FileWriteMode, content: string) {
    const file = normalize(relative_file);

    if (!this.changes[file]) {
      this.changes[file] = { mode, content };
    } else if (
      mode === FileWriteMode.append &&
      this.changes[file].mode === FileWriteMode.append
    ) {
      this.changes[file].content += "\n" + content;
    } else {
      throw new Error(`File ${file} has already been staged for changes.`);
    }
  }

  /**
   * Marks `path` as generated: `applyChanges` deletes the files under it that
   * weren't staged and start with the generated header.
   */
  own(path: string) {
    this.owned.add(normalize(path));
  }

  /**
   * Formats every staged file and compares it with what's on disk, without
   * writing anything.
   */
  async plan(format?: Formatter): Promise<PlannedChange[]> {
    const planned: PlannedChange[] = [];
    const ownedDirs = [...this.owned];

    for (const [file, change] of Object.entries(this.changes)) {
      const fullPath = join(this.root, file);

      if (change.mode === FileWriteMode.initialise) {
        // Also left alone when its extensionless sibling exists, so a handler
        // `Foo.py` can be turned into a `Foo/` package.
        const exists =
          existsSync(fullPath) ||
          existsSync(fullPath.split(".").slice(0, -1).join("."));
        if (exists) {
          planned.push({ file, action: "unchanged" });
          continue;
        }
      }

      let content = change.content || "";
      if (format) {
        try {
          content = await format(content, fullPath);
        } catch (err) {
          console.warn(
            `Could not format ${fullPath}, writing raw content instead.`,
            err,
          );
        }
      }

      // Added after formatting so a formatter can't move it off the first
      // line, where stale-file removal looks for it.
      const header =
        change.mode !== FileWriteMode.initialise &&
        ownedDirs.some((dir) => isWithin(file, dir))
          ? headerByExtension[extname(file).slice(1)]
          : undefined;
      if (header) content = header + content;

      if (!existsSync(fullPath)) {
        planned.push({ file, action: "create", content });
      } else if (readFileSync(fullPath, "utf-8") !== content) {
        planned.push({ file, action: "update", content });
      } else {
        planned.push({ file, action: "unchanged" });
      }
    }

    for (const dir of ownedDirs) {
      const fullDir = join(this.root, dir);
      if (!existsSync(fullDir)) continue;
      for (const entry of readdirSync(fullDir, {
        recursive: true,
        withFileTypes: true,
      })) {
        if (!entry.isFile()) continue;
        const file = relative(this.root, join(entry.parentPath, entry.name));
        // Files other tools write here (no marker) are left alone.
        if (!this.changes[file] && hasGeneratedHeader(join(this.root, file))) {
          planned.push({ file, action: "remove" });
        }
      }
    }

    return planned;
  }

  /**
   * Writes created and updated files and removes stale ones under owned
   * directories. Everything is formatted before anything is written, so a
   * failure leaves disk untouched. With `check`, nothing is written.
   */
  async applyChanges(
    format?: Formatter,
    { check = false }: { check?: boolean } = {},
  ): Promise<WriteMetrics> {
    const planned = await this.plan(format);
    const count = (action: PlannedAction) =>
      planned.filter((change) => change.action === action).length;
    const changed = planned.filter((change) => change.action !== "unchanged");

    if (!check) {
      for (const { file, action, content } of changed) {
        const fullPath = join(this.root, file);
        if (action === "remove") {
          rmSync(fullPath, { force: true });
        } else {
          mkdirSync(dirname(fullPath), { recursive: true });
          writeFileSync(fullPath, content ?? "");
        }
      }
      for (const dir of this.owned) removeEmptyDirs(join(this.root, dir));
      this.changes = {};
      this.owned.clear();
    }

    return {
      created: count("create"),
      updated: count("update"),
      removed: count("remove"),
      unchanged: count("unchanged"),
      linesInChanges: changed.reduce(
        (lines, { content }) => lines + (content?.match(/\n/g)?.length ?? 0),
        0,
      ),
      changed,
    };
  }

  getScope(relativeRoot: string): Scope {
    return new Scope(this, relativeRoot);
  }
}

/** Removes the empty directories below `dir` (not `dir` itself), deepest first. */
function removeEmptyDirs(dir: string) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const child = join(dir, entry.name);
    removeEmptyDirs(child);
    if (readdirSync(child).length === 0) rmSync(child, { recursive: true });
  }
}

export class Scope extends FileWriter {
  fileWriter: FileWriter;
  constructor(fileWriter: FileWriter, relativeRoot: string) {
    if (fileWriter instanceof Scope) {
      super(join(fileWriter.root, relativeRoot));
      this.fileWriter = fileWriter.fileWriter;
    } else {
      super(relativeRoot);
      this.fileWriter = fileWriter;
    }
  }

  stageFileChange(relative_file: string, mode: FileWriteMode, content: string) {
    this.fileWriter.stageFileChange(
      join(this.root, relative_file),
      mode,
      content,
    );
  }

  readFile(filePath: string): string {
    return this.fileWriter.readFile(join(this.root, filePath));
  }

  own(path: string) {
    this.fileWriter.own(join(this.root, path));
  }

  async plan(): Promise<PlannedChange[]> {
    throw new Error(
      "Cannot plan changes from a Scope. Call plan on the parent FileWriter instead.",
    );
  }

  async applyChanges(): Promise<WriteMetrics> {
    throw new Error(
      "Cannot apply changes from a Scope. Call applyChanges on the parent FileWriter instead.",
    );
  }
}
